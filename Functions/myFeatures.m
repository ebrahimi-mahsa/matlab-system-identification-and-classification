function Uref = myFeatures(U,center)
% myFeatures creates the quadratic feature set.
% U contains the original two features.
% center is the mean calculated from the training set.

    X = U - center;

    Uref = [ ...
        X(:,1), ...
        X(:,2), ...
        X(:,1).^2, ...
        X(:,1).*X(:,2), ...
        X(:,2).^2 ];

end